function ThreeDimensionMap() {
  const [fillOpacity, setFillOpacity] = useState(1);
  const ref = useRef<HTMLDivElement | null>(null);
  const [, setMap] = useState<mapboxgl.Map | null>(null);

  useEffect(() => {
    if (ref?.current && typeof ref?.current !== undefined) {
      const m = new mapboxgl.Map({
        container: ref?.current || "",
        center: [86.354136636877, 23.686980736124],
        zoom: 13.1,
        pitch: 85,
        bearing: 80,
        style: "mapbox://styles/mapbox-map-design/ckhqrf2tz0dt119ny6azh975y",
      });
      setMap(m);

      m.on("load", () => {
        m.addSource("mapbox-dem", {
          type: "raster-dem",
          url: "mapbox://mapbox.mapbox-terrain-dem-v1",
          tileSize: 512,
          maxzoom: 14,
        });
        m.setTerrain({ source: "mapbox-dem", exaggeration: 1.5 });
        m.addLayer({
          id: "sky",
          type: "sky",
          paint: {
            "sky-type": "atmosphere",
            "sky-atmosphere-sun": [0.0, 0.0],
            "sky-atmosphere-sun-intensity": 15,
          },
        });

        const fogOpts = {
          range: [2, 12],
          color: "white",
          "horizon-blend": 0.1,
        };
        m.setFog(fogOpts);

        // Add polygon layer
        m.addLayer({
          id: "polygon",
          type: "fill",
          source: {
            type: "geojson",
            data: {
              type: "Feature",
              geometry: {
                type: "Polygon",
                coordinates: [
                  polygonCoordinates.map((coord) => [coord.lng, coord.lat]),
                ],
              },
            },
          },
          paint: {
            "fill-color": "#0ede00",
            "fill-opacity": fillOpacity,
          },
        });
      });
    }
  }, [ref]);

  return (
    <div id="map-container" style={{ height: "100vh" }} ref={ref}>
      <ActionSection />
      <div className="flex justify-center">
        <RangeSlider
          min={0}
          max={1}
          step={0.0001}
          className="absolute left-[10] top-[10] block bottom-10 z-[1000] w-100 "
          value={fillOpacity}
          onChange={(e) => setFillOpacity(e.target.value)}
        />
      </div>
    </div>
  );
}

export default ThreeDimensionMap;
